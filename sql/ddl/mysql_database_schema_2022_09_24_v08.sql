CREATE TABLE creatures (
	pk_creature_id INT PRIMARY KEY AUTO_INCREMENT,
	title VARCHAR(32) UNIQUE,
	mana_cost VARCHAR(8),
	converted_mana_cost INT,
	kind VARCHAR(32),
	fk_extension INT,
	fk_rarity INT,
	rules_text VARCHAR(664),
	flavor_text VARCHAR(200),
	punch INT,
	toughness INT,
	fk_artist INT,
	collector_number INT,
	fk_collections_instance INT AUTO_INCREMENT,
	FOREIGN KEY (fk_extension) REFERENCES extensions(pk_extensions_id),
	FOREIGN KEY (fk_rarity) REFERENCES rarities(pk_rarities_id),
	FOREIGN KEY (fk_artist) REFERENCES artists(pk_artists_id)
);

CREATE TABLE noncreatures (
	pk_creature_id INT PRIMARY KEY AUTO_INCREMENT,
	title VARCHAR(32) UNIQUE,
	mana_cost VARCHAR(8),
	converted_mana_cost INT,
	kind VARCHAR(32),
	fk_extension INT,
	fk_rarity INT,
	rules_text VARCHAR(664),
	flavor_text VARCHAR(200),
	fk_artist INT,
	collector_number INT,
	fk_collections_instance INT AUTO_INCREMENT=11699,
	FOREIGN KEY (fk_extension) REFERENCES extensions(pk_extensions_id),
	FOREIGN KEY (fk_rarity) REFERENCES rarities(pk_rarities_id),
	FOREIGN KEY (fk_artist) REFERENCES artists(pk_artists_id)
);

CREATE TABLE planeswalkers (
	pk_creature_id INT PRIMARY KEY AUTO_INCREMENT,
